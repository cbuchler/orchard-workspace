const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../shell/methodOverrides.js'), 'utf8')
    .replace('export class MethodOverrides', 'class MethodOverrides');
const {MethodOverrides} = vm.runInNewContext(`${source}\n({MethodOverrides})`);
const owner = new MethodOverrides();
const prototype = {run(value) { return this.value + value; }};
const object = Object.assign(Object.create(prototype), {value: 2});
owner.add(object, 'run', original => function (value) { return original.call(this, value) * 3; });
assert.equal(object.run(4), 18);
const retained = object.run;
const hook = owner._hooks[0];
const later = function (value) { return retained.call(this, value) + 1; };
object.run = later;
owner.clear();
assert.equal(object.run, later, 'do not overwrite a later extension');
assert.equal(object.run(4), 7, 'retained wrapper becomes a native pass-through');
assert.equal(hook.override, null, 'retained wrapper no longer retains extension callback');
assert.equal(hook.object, null, 'retained wrapper no longer retains target actor');
assert.equal(hook.descriptor, null);
delete object.run;
owner.add(object, 'run', original => original);
owner.clear();
assert(!Object.hasOwn(object, 'run'), 'restore inherited method without an own-property shadow');
const descriptor = {value: prototype.run, enumerable: false, configurable: true, writable: true};
Object.defineProperty(object, 'run', descriptor);
owner.add(object, 'run', () => () => 42);
owner.clear();
assert.deepEqual(Object.getOwnPropertyDescriptor(object, 'run'), descriptor);
owner.add(object, 'run', original => original);
owner.forgetObject(object);
Object.defineProperty(object, 'run', {get() { throw new Error('destroyed actor was accessed'); }});
owner.clear();
assert.equal(owner._hooks.length, 0, 'clear never accesses a destroyed actor');
console.log('PASS: method descriptor restoration, later extension chaining, closure detachment and destroyed actor cleanup');
